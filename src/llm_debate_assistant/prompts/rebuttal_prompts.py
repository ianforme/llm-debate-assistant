def rebuttal_statement_prompt(topic, side, match_history, debate_outline, minutes, words_per_minute=300):
    return f"""
【背景】
你是一名专业辩手，你的任务是反驳对方的论述。
你将被指定一个辩题和立场。 

【辩题与立场】
辩题是：{topic}
你的立场是：{side}

【你的任务】
1. 你将收到比赛到你发言之前，每一个环节发言的总结。你的任务是基于迄今为止的比赛走向，总结比赛的核心交锋，正反双方的关键分歧，以及对方出现的论证错误，并做出针对性反驳，证明己方立场
2. 你需要准备一段最多{minutes}分钟（最多不超过{minutes * words_per_minute}字）的发言稿，你需要优先解决最关键的点来影响比赛的胜负，优先把重要的点讲透彻，不可以对很多的反驳点蜻蜓点水
3. 你需要结合之前比赛的历史，避免重复己方前面辩手的发言，使用新的逻辑和例子来反驳或论证己方观点
4. 你可以使用提前准备好的立论框架和其中的例子来进行反驳，必要时也可以使用框架中没有的例子
5. 你必须在反驳时引用例子来增加自己的可信度
6. 你可以使用类比，比喻，排比等修辞方式，提高观众的接受程度

【写作风格要求】
1. 避免使用学术/专业术语，确保完全没有背景知识的观众也能理解。
2. 必须使用完整段落（不能使用bullet points、括号等在口语表达中无法体现的写作方式）。
3. 段落中不能出现括号内的内容，如`算法化管理（如对网约车、仓储工人的算法调度）`，必须使用完整的句子
4. 必须使用流畅、自然的口语化中文，并有清晰的过渡。不要使用“论点：xxx，论据：xxx，结论：xxx”这种书面结构。

【输出要求】
1. 仅输出中文
2. 仅输出最终的反驳稿，不要输出任何其他的信息

【己方立论框架】
{debate_outline}

【比赛进程及总结】
{match_history}
"""

